for r in routes:
    rid = r["route_id"]
    assert rid not in seen, "duplicate " + rid
    seen.add(rid)
    assert rid.startswith("R70") and rid <= "R7099", "out of range " + rid
    keys = sorted(r.keys())
    if r["verdict"] == "verify":
        assert len(keys) == 24, (rid, len(keys), keys)
    else:
        assert len(keys) == 19, (rid, len(keys), keys)
        assert r["payout_quote"] is None and r["steps"] == [] and r["timing"] is None
    assert r["checked_at"] == CHECKED
    assert set(r["critical"].keys()) == {"c1", "c2", "c3", "c4"}
    assert set(r["standard"].keys()) == {"s1", "s2", "s3", "s4", "s5", "s6", "s7"}
    assert set(r["weasel_words"].keys()) == {"present", "quote"}
    assert set(r["repeatable"].keys()) == {"value", "cadence"}
    assert isinstance(r["maximize"], str)
    assert r["upfront_fee"] is False
    with open(os.path.join(OUT, rid + ".json"), "w") as f:
        json.dump(r, f, indent=2, sort_keys=True)
        f.write("\n")

